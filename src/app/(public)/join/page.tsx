"use client";

import { Check, Clock, Hourglass, QrCode, Search } from "lucide-react";
import { useState, type FormEvent } from "react";
import { Money } from "@/components/domain";
import { OnlineJoin } from "@/components/online-join";
import { useVisitor } from "@/components/public-shell";
import {
  Badge,
  Button,
  Card,
  FileField,
  FormError,
  LinkButton,
  Notice,
  PageHeader,
  SelectField,
  Skeleton,
  TextField,
} from "@/components/ui";
import { api, errorMessage, fieldErrors, useApi } from "@/lib/api-client";
import {
  APPLICATION_METHODS,
  APPLICATION_METHOD_LABELS,
  SETTINGS,
  type ApplicationMethod,
  type ApplicationReceipt,
  type ApplicationStatusView,
  type PaymentInstructions,
} from "@/lib/contracts";
import { formatDateTime } from "@/lib/dates";

const BENEFITS = [
  "Member prices on event tickets",
  "Member prices on hoodies and T-shirts",
  "Your own account: tickets, orders and tasks in one place",
  "A vote at the annual general meeting",
];

const MAX_IMAGE_BYTES = 5 * 1024 * 1024;

const REFERENCE_HELP: Record<ApplicationMethod, { label: string; hint: string }> = {
  upi: { label: "UPI reference number", hint: "The 12-digit UTR or reference shown in your UPI app after paying." },
  bank: { label: "Bank reference number", hint: "The transaction reference from your bank's confirmation." },
  cash: { label: "Who did you pay?", hint: "The committee member you handed the cash to, and when." },
};

function PaymentStep({ instructions }: { instructions: PaymentInstructions | null }) {
  if (!instructions) return <Skeleton className="h-40" />;
  return (
    <div className="flex flex-col gap-5 sm:flex-row sm:items-start">
      {instructions.upi ? (
        <div className="shrink-0 self-center rounded-card border border-line bg-white p-3 sm:self-start">
          <div
            role="img"
            aria-label={`UPI payment code for ${instructions.upi.vpa}`}
            className="ticket-qr size-40"
            // The SVG is generated by the server from the configured UPI ID.
            dangerouslySetInnerHTML={{ __html: instructions.upi.qrSvg }}
          />
        </div>
      ) : (
        <div className="flex size-40 shrink-0 flex-col items-center justify-center gap-2 self-center rounded-card border border-dashed border-line-strong px-3 text-center text-[0.8125rem] text-muted sm:self-start">
          <QrCode className="size-6" aria-hidden />
          No payment code is set up yet
        </div>
      )}
      <div className="min-w-0 text-sm">
        <p className="font-display text-2xl font-bold text-ink">
          <Money cents={instructions.feeCents} />
        </p>
        {instructions.upi ? (
          <>
            <p className="mt-1">
              Scan the code with any UPI app, or pay <span className="break-all font-mono text-ink">{instructions.upi.vpa}</span> ({instructions.upi.payeeName}).
            </p>
            <p className="mt-2 text-muted">Keep the confirmation screen. You will need its reference number and a screenshot below.</p>
          </>
        ) : (
          <p className="mt-1">
            Pay the treasurer in cash, or ask the committee for the club&rsquo;s bank details. Then fill in the form below.
          </p>
        )}
        <p className="mt-2 text-muted">
          Scanning the code or sending this form does not confirm your payment. The treasurer checks the club&rsquo;s account and approves each
          application by hand.
        </p>
      </div>
    </div>
  );
}

function StatusLookup() {
  const [code, setCode] = useState("");
  const [email, setEmail] = useState("");
  const [result, setResult] = useState<ApplicationStatusView | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [working, setWorking] = useState(false);

  async function look(e: FormEvent) {
    e.preventDefault();
    setWorking(true);
    setError(null);
    setResult(null);
    try {
      setResult(await api<ApplicationStatusView>("/api/public/applications/status", { method: "POST", body: { code, email } }));
    } catch (err) {
      setError(errorMessage(err));
    } finally {
      setWorking(false);
    }
  }

  return (
    <Card className="p-5">
      <h2 className="text-[0.9375rem] font-semibold">Already applied?</h2>
      <form onSubmit={look} noValidate className="mt-3 space-y-3">
        <TextField label="Application code" placeholder="APP-XXXXXX" autoCapitalize="characters" value={code} onChange={(e) => setCode(e.target.value)} required />
        <TextField label="Email you applied with" type="email" autoComplete="email" value={email} onChange={(e) => setEmail(e.target.value)} required />
        <Button type="submit" variant="secondary" icon={Search} loading={working}>
          Check status
        </Button>
      </form>
      <div aria-live="polite" className="mt-3 text-sm">
        {error && <p className="text-bad">{error}</p>}
        {result?.status === "pending" && !result.online && (
          <Notice tone="warn" icon={Hourglass} title="Waiting for the treasurer">
            Sent {formatDateTime(result.submittedAt)}. Your payment has not been verified yet.
          </Notice>
        )}
        {result?.status === "pending" && result.online === "needs_review" && (
          <Notice tone="warn" icon={Hourglass} title="Payment received">
            The committee is finishing your membership by hand. You do not need to pay again.
          </Notice>
        )}
        {result?.status === "pending" && result.online === "refunded" && (
          <Notice tone="warn" title="This payment was refunded">
            You can apply again.
          </Notice>
        )}
        {result?.status === "pending" && result.online && result.online !== "needs_review" && result.online !== "refunded" && (
          <Notice tone="warn" icon={Hourglass} title="Not paid yet">
            Started {formatDateTime(result.submittedAt)}. No payment has been confirmed. Open this page in the browser you applied from to
            pay, or apply again.
          </Notice>
        )}
        {result?.status === "approved" && (
          <Notice tone="ok" icon={Check} title={`Approved. Your member ID is ${result.memberNo}`}>
            If you do not have a link to set your password, ask the committee for one.
          </Notice>
        )}
        {result?.status === "rejected" && (
          <Notice tone="bad" title="Not approved">
            {result.reviewNote ?? "The committee could not verify this payment."} You can apply again.
          </Notice>
        )}
      </div>
    </Card>
  );
}

export default function JoinPage() {
  const instructions = useApi<PaymentInstructions>("/api/public/membership");
  const [values, setValues] = useState({ name: "", email: "", studentId: "", phone: "", paymentReference: "" });
  const [method, setMethod] = useState<ApplicationMethod>("upi");
  const [evidence, setEvidence] = useState<File | null>(null);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const [formError, setFormError] = useState<string | null>(null);
  const [working, setWorking] = useState(false);
  const [receipt, setReceipt] = useState<ApplicationReceipt | null>(null);
  const online = instructions.data?.online.available === true;
  const visitor = useVisitor();
  // Someone signed in as a member has nothing to apply for. The server refuses it as well.
  const member = visitor?.role === "member" ? visitor : null;

  const set = (key: keyof typeof values) => (e: { target: { value: string } }) =>
    setValues((v) => ({ ...v, [key]: e.target.value }));

  async function submit(e: FormEvent) {
    e.preventDefault();
    setFormError(null);
    if (evidence && evidence.size > MAX_IMAGE_BYTES) {
      setErrors({ evidence: "The image must be 5 MB or smaller" });
      return;
    }
    setErrors({});
    setWorking(true);
    try {
      const form = new FormData();
      for (const [key, value] of Object.entries(values)) form.set(key, value);
      form.set("paymentMethod", method);
      if (evidence) form.set("evidence", evidence);
      setReceipt(await api<ApplicationReceipt>("/api/public/applications", { method: "POST", form }));
    } catch (error) {
      setErrors(fieldErrors(error));
      setFormError(errorMessage(error));
    } finally {
      setWorking(false);
    }
  }

  // The manual route: pay outside Skyline, then send the details for the treasurer to check.
  const manual = (
    <>
      <Card className="p-5">
        <h2 className="mb-4 text-[0.9375rem] font-semibold">
          <span className="mr-2 inline-flex size-6 items-center justify-center rounded-full bg-brand text-xs font-bold text-on-brand">1</span>
          Pay the membership fee
        </h2>
        <PaymentStep instructions={instructions.data} />
      </Card>

      <Card className="p-5">
        <h2 className="mb-4 text-[0.9375rem] font-semibold">
          <span className="mr-2 inline-flex size-6 items-center justify-center rounded-full bg-brand text-xs font-bold text-on-brand">2</span>
          Tell us about you and your payment
        </h2>
        <form onSubmit={submit} noValidate className="space-y-4">
          <FormError message={formError} />
          <TextField label="Full name" autoComplete="name" value={values.name} onChange={set("name")} error={errors.name} required />
          <TextField
            label="Email"
            type="email"
            autoComplete="email"
            value={values.email}
            onChange={set("email")}
            error={errors.email}
            hint="You will sign in with this once your membership is approved."
            required
          />
          <div className="grid gap-4 sm:grid-cols-2">
            <TextField label="Student ID" value={values.studentId} onChange={set("studentId")} error={errors.studentId} optional />
            <TextField label="Phone" type="tel" autoComplete="tel" value={values.phone} onChange={set("phone")} error={errors.phone} optional />
          </div>
          <div className="grid gap-4 sm:grid-cols-2">
            <SelectField label="How did you pay?" value={method} onChange={(e) => setMethod(e.target.value as ApplicationMethod)} error={errors.paymentMethod}>
              {APPLICATION_METHODS.map((m) => (
                <option key={m} value={m}>
                  {APPLICATION_METHOD_LABELS[m]}
                </option>
              ))}
            </SelectField>
            <TextField
              label={REFERENCE_HELP[method].label}
              value={values.paymentReference}
              onChange={set("paymentReference")}
              error={errors.paymentReference}
              hint={REFERENCE_HELP[method].hint}
              required
            />
          </div>
          <FileField
            label="Screenshot of the payment"
            onFile={setEvidence}
            error={errors.evidence}
            optional={method === "cash"}
            hint="JPEG, PNG or WebP, up to 5 MB. Only the treasurer and president can see it."
          />
          <Button type="submit" size="lg" loading={working}>
            Send application
          </Button>
          <p className="text-[0.8125rem] text-muted">
            Your details are visible only to the committee and are used to run the club.
          </p>
        </form>
      </Card>
    </>
  );

  return (
    <>
      <PageHeader
        title="Become a member"
        description={
          <>
            Membership costs <Money cents={SETTINGS.membershipFeeCents} /> and runs until 31 December.{" "}
            {member
              ? ""
              : online
              ? "Pay online and your membership starts straight away."
              : "Pay the fee, send us the payment details, and the treasurer will confirm it."}
          </>
        }
      />
      <div className="grid gap-6 lg:grid-cols-[1fr_22rem]">
        <div className="space-y-6">
          {member ? (
            <Card className="p-5">
              <Notice tone="ok" icon={Check} title={`You are already a member (${member.memberNo})`}>
                You are signed in as {member.name}. There is nothing to pay or apply for here.
              </Notice>
              <div className="mt-5 flex flex-wrap gap-3">
                <LinkButton href="/member/membership">My membership</LinkButton>
                <LinkButton href="/member" variant="secondary">
                  Member dashboard
                </LinkButton>
              </div>
            </Card>
          ) : visitor === undefined ? (
            // Not known yet whether this is a member; do not offer a form that might then disappear.
            <Card className="p-5">
              <Skeleton className="h-40" />
            </Card>
          ) : receipt ? (
            <Card className="p-5">
              <Notice tone="warn" icon={Clock} title="Application received. It is not approved yet.">
                The treasurer will check the club&rsquo;s account for your payment. You are not a member until they approve it.
              </Notice>
              <dl className="mt-5 space-y-3 text-sm">
                <div>
                  <dt className="text-muted">Your application code</dt>
                  <dd className="font-mono text-2xl font-bold text-ink">{receipt.code}</dd>
                </div>
                <div>
                  <dt className="text-muted">Amount you told us you paid</dt>
                  <dd className="text-lg font-semibold text-ink">
                    <Money cents={receipt.amountCents} />
                  </dd>
                </div>
                <div>
                  <dt className="text-muted">Status</dt>
                  <dd>
                    <Badge tone="warn">Pending verification</Badge>
                  </dd>
                </div>
              </dl>
              <p className="mt-4 text-sm">
                Write the code down. Use it with your email in &ldquo;Already applied?&rdquo; to check progress. Once approved you get a member
                ID and a link to set your password.
              </p>
              <LinkButton href="/events" variant="secondary" className="mt-5">
                Browse events
              </LinkButton>
            </Card>
          ) : (
            <>
              {online && <OnlineJoin />}
              {!instructions.data && !instructions.error ? (
                // Not known yet whether online payment is on; avoid showing the manual form and then moving it.
                <Card className="p-5">
                  <Skeleton className="h-40" />
                </Card>
              ) : online ? (
                <details className="group">
                  <summary className="cursor-pointer rounded-control px-1 py-2 text-sm font-medium text-muted hover:text-ink">
                    Pay by cash, bank transfer or direct UPI transfer instead
                  </summary>
                  <div className="mt-4 space-y-6">{manual}</div>
                </details>
              ) : (
                manual
              )}
            </>
          )}
        </div>

        <div className="space-y-6">
          <Card className="h-fit p-5">
            <h2 className="text-[0.9375rem] font-semibold">What you get</h2>
            <ul className="mt-3 space-y-2.5 text-sm">
              {BENEFITS.map((benefit) => (
                <li key={benefit} className="flex items-start gap-2.5">
                  <Check className="mt-0.5 size-4 shrink-0 text-ok" aria-hidden />
                  {benefit}
                </li>
              ))}
            </ul>
          </Card>
          {!member && <StatusLookup />}
        </div>
      </div>
    </>
  );
}
